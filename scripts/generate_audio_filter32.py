"""Offline 32 kHz source filter: 668-tap, 11 kHz Kaiser-windowed sinc.
No floating point runs on the Amiga. Symmetric Q20 taps preserve unity DC gain.
The 11 kHz corner leaves a transition band before the 16 kHz Nyquist limit.
"""
import argparse,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TAPS=668
CLOCKS={'ntsc':1789772.7272727273,'pal':1662607.125}

def i0(x):
    term=total=1.0
    for k in range(1,40):
        term*=x*x/(4*k*k);total+=term
    return total

def coefficients(clock):
    values=[];beta=5.65
    for k in range(TAPS):
        x=k-(TAPS-1)/2
        sinc=math.sin(2*math.pi*11000*x/clock)/(math.pi*x)
        window=i0(beta*math.sqrt(1-(2*k/(TAPS-1)-1)**2))/i0(beta)
        values.append(sinc*window)
    gain=sum(values)
    taps=[int(v/gain*(1<<20)) for v in values]
    # Equal middle taps keep exact symmetry and exact unity DC gain.
    delta=((1<<20)-sum(taps))//2
    taps[TAPS//2-1]+=delta;taps[TAPS//2]+=delta
    assert taps==taps[::-1] and sum(taps)==1<<20
    return taps

def render():
    text='/* Generated by scripts/generate_audio_filter32.py; GPL-3.0-or-later. */\n'
    text+='#define FC_AUDIO_32_TAPS 668\n'
    for name,clock in CLOCKS.items():
        taps=coefficients(clock)[:TAPS//2]
        text+=f'static const int32 fc_audio_32_{name}[FC_AUDIO_32_TAPS/2]={{\n'
        text+='\n'.join(' '+','.join(map(str,taps[i:i+8]))+',' for i in range(0,len(taps),8))+'\n};\n'
    return text

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    out=ROOT/'development/output-quality-20261030/audio_filter32.h'
    if a.check:assert out.read_text()==render()
    else:out.write_text(render())
    print('PASS reproducible 668-tap PAL/NTSC 32 kHz filters')
if __name__=='__main__':main()
